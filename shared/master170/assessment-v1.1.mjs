// Presentation only. Reveal a focused/active question after its map resizes.
// Never react to timers/autosave, rebuild DOM, focus an input or scroll a pane.
export function installQuestionMapVisibility(root=document.body) {
  if(!root?.matches('[data-izone-design="master170@1.1"][data-izone-ui-profile="exam-compact"]'))return ()=>{};
  const widths=new WeakMap();
  const reveal=(nav,button)=>{
    if(!button||!nav.contains(button))return;
    const box=nav.getBoundingClientRect(),target=button.getBoundingClientRect();
    if(box.width<=0||box.height<=0)return;
    if(target.left<box.left)nav.scrollLeft-=box.left-target.left+2;
    else if(target.right>box.right)nav.scrollLeft+=target.right-box.right+2;
  };
  const resized=new ResizeObserver(entries=>{
    for(const {target:nav}of entries){
      const width=nav.clientWidth,old=widths.get(nav);widths.set(nav,width);
      if(old===undefined||width===old)continue;
      const focused=nav.contains(document.activeElement)?document.activeElement.closest('.cbt-question-button'):null;
      reveal(nav,focused||nav.querySelector('.cbt-question-button.is-active,.cbt-question-button[aria-current="true"]'));
    }
  });
  const register=node=>{
    if(!(node instanceof Element))return;
    const maps=node.matches('#readingView .cbt-question-nav')?[node]:node.querySelectorAll('#readingView .cbt-question-nav');
    for(const nav of maps)if(!widths.has(nav)){widths.set(nav,nav.clientWidth);resized.observe(nav);}
  };
  register(root);
  const unregister=node=>{
    if(!(node instanceof Element))return;
    const maps=node.matches('.cbt-question-nav')?[node]:node.querySelectorAll('.cbt-question-nav');
    for(const nav of maps)if(widths.has(nav)){resized.unobserve(nav);widths.delete(nav);}
  };
  const added=new MutationObserver(entries=>{for(const entry of entries){for(const node of entry.removedNodes)unregister(node);for(const node of entry.addedNodes)register(node);}});
  added.observe(root,{childList:true,subtree:true});
  const focus=event=>{const button=event.target.closest?.('.cbt-question-button'),nav=button?.closest('#readingView .cbt-question-nav');if(nav)reveal(nav,button);};
  root.addEventListener('focusin',focus);
  return ()=>{added.disconnect();resized.disconnect();root.removeEventListener('focusin',focus);};
}
installQuestionMapVisibility();

// Keep native button nodes/listeners. Only replace decorative arrows or add a
// Notes icon; SVG children cannot become a different pointer-event target.
export function installButtonIcons(root=document.body) {
  if(!root?.matches('[data-izone-design="master170@1.1"]'))return ()=>{};
  const sprite=new URL('./icons.svg?v=20261028-master11',import.meta.url).href;
  const decorate=button=>{
    if(!(button instanceof HTMLButtonElement)||button.querySelector('svg:not(.m170-icon)'))return;
    // Native renderers change an existing button's text between chapters and
    // pending states. Remove only a name generated by this helper when stale;
    // an explicit name owned by the native renderer must remain untouched.
    const generated=button.dataset.m170GeneratedLabel;
    if(generated){
      if(button.getAttribute('aria-label')===generated&&button.textContent.trim()!==button.dataset.m170DecoratedText)button.removeAttribute('aria-label');
      if(button.getAttribute('aria-label')!==generated)delete button.dataset.m170GeneratedLabel;
    }
    if(button.dataset.m170Icon&&button.querySelector('svg.m170-icon'))return;
    const text=button.textContent.trim();let icon,label=text,preserveName=false;
    if(button.matches('.cbt-tool-button,#notes-button,.header-notes')&&/^(Notes|Ghi chú)$/.test(text))icon='notes';
    else if(button.closest('.explanation-dialog-footer')&&/^(←\s*)?Câu trước$/.test(text)){icon='previous';label='Câu trước';}
    else if(button.closest('.explanation-dialog-footer')&&/^Câu sau(\s*→)?$/.test(text)){icon='next';label='Câu sau';}
    // Plain native arrow labels include Homework repair/stepper/entry buttons.
    // Never replace structured labels, counters, form controls or native SVGs.
    else if(!button.children.length&&/^←\s*\S/.test(text)){icon='previous';label=text.replace(/^←\s*/,'');preserveName=true;}
    else if(!button.children.length&&/\S\s*→$/.test(text)){icon='next';label=text.replace(/\s*→$/,'');preserveName=true;}
    else if(!button.children.length&&button.matches('.replay-button,#replay-review')){icon='play';label=text.replace(/^[▷▶]\s*/,'');}
    if(!icon)return;
    if(preserveName&&!button.hasAttribute('aria-label')){button.setAttribute('aria-label',text);button.dataset.m170GeneratedLabel=text;}
    const svg=document.createElementNS('http://www.w3.org/2000/svg','svg');svg.classList.add('m170-icon');svg.setAttribute('viewBox','0 0 24 24');svg.setAttribute('aria-hidden','true');svg.setAttribute('focusable','false');
    const use=document.createElementNS('http://www.w3.org/2000/svg','use');use.setAttribute('href',sprite+'#'+icon);svg.append(use);
    button.dataset.m170Icon=icon;button.dataset.m170DecoratedText=label;
    if(icon==='next')button.replaceChildren(document.createTextNode(label),svg);
    else button.replaceChildren(svg,document.createTextNode(label));
  };
  const scan=node=>{if(!(node instanceof Element))return;decorate(node.closest('button'));for(const button of node.querySelectorAll('button'))decorate(button);};
  scan(root);
  const observer=new MutationObserver(entries=>{for(const entry of entries){decorate(entry.target.closest?.('button'));for(const node of entry.addedNodes)scan(node);}});
  observer.observe(root,{childList:true,subtree:true});
  return ()=>observer.disconnect();
}
installButtonIcons();
