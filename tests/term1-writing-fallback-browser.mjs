import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { randomUUID } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import vm from 'node:vm';
import test from 'node:test';
import { fixture as browserFixture, wait } from './term2-offline-browser.mjs';

test('Writing dự phòng giữ Task 2 offline và bài trắng nhận 0 không có job AI', { timeout: 65000 }, async t => {
  const { TERM2_EVIDENCE: output, TERM1_FALLBACK_BACKEND: backend, TERM2_RUNTIME_ROOT: runtime, TERM2_DEPS_PACKAGE: deps } = process.env;
  assert.ok(output && backend && runtime && deps);
  process.env.K56_TEST_PRODUCT = '1';
  process.env.TERM2_FIXTURE_IMPORT_ONLY = '1';
  const { fixture } = await import(pathToFileURL(resolve(backend, 'backend/ops/releases/term1-offline-20261107/test.mjs')));
  const { registerTerm1SkillRoutes } = await import(pathToFileURL(resolve(runtime, 'src/term1-skill-routes.mjs')));
  const { studentWritingGrading, WRITING_RELEASE_DELAY_MS } = await import(pathToFileURL(resolve(runtime, 'src/k56-student-writing-release.mjs')));
  const require = createRequire(deps), express = require('express');
  const native = await fixture('lis_first', { skipPrepare: true, realtime: true });
  t.after(native.close);
  const sandbox = { window: {} };
  vm.runInNewContext(await readFile(new URL('../term-tests/term-test-1-k56-computer-based/content.js', import.meta.url), 'utf8'), sandbox);
  native.content.writing = sandbox.window.K56_TERM_TEST_CONTENT.writing;
  const studentRef = randomUUID(), scope = { classCode: 'IC5601', studentRef, section: 'writing' };
  const app = express(), router = express.Router(), noop = (_req, _res, next) => next();
  let afterRelease = false;
  app.use(express.json());
  registerTerm1SkillRoutes(router, { authenticate: noop, readTeacherScope: async (_db, input) => assert.equal(input.student, studentRef),
    transaction: work => native.db.transaction(work), prepare: (slug, _input, _create, db) => native.load(db, slug, native.a), load: native.load,
    findStudent: async () => ({ class_id: '5601', student_id: '5602' }), assets: {}, policy: 'term1-offline-v1', limiter: noop, readLimiter: noop,
    allowNew: () => true, readWriting: async (client, attempt) => studentWritingGrading(attempt.test_slug,
      await native.grading.getStatus(attempt.attempt_token, client), Date.now() + (afterRelease ? WRITING_RELEASE_DELAY_MS + 1000 : 0)) });
  app.use('/api/term-tests', router);
  const server = app.listen(0, '127.0.0.1');
  await new Promise(done => server.once('listening', done));
  t.after(() => new Promise(done => server.close(done)));
  const skillsApi = 'http://127.0.0.1:' + server.address().port + '/api/term-tests/term-test-1-k56/skill-fallback';
  const { body: grant } = await require('supertest')(app).post('/api/term-tests/term-test-1-k56/skill-fallback/issue').send(scope).expect(200);
  const browser = await browserFixture('read_first', { product: 1 });
  t.after(browser.close);
  const page = browser.page;
  const link = new URL('../term-test-1-k56-writing-fallback/?class=IC5601', browser.url);
  link.hash = new URLSearchParams({ g: grant.token });
  let disconnected = false, lost = false;
  await browser.context.route('**/api/term-tests/term-test-1-k56/**', async route => {
    const request = route.request(), cors = { 'access-control-allow-origin': '*', 'access-control-allow-headers': '*', 'access-control-allow-methods': 'POST,OPTIONS' };
    if (request.method() === 'OPTIONS') return route.fulfill({ status: 204, headers: cors });
    if (disconnected) return route.abort();
    const relative = new URL(request.url()).pathname.split('/term-test-1-k56/')[1];
    assert.match(relative, /^(?:skill-fallback|offline)\//);
    assert.equal(request.headers()['x-term1-skill-grant'], grant.token);
    const destination = relative.startsWith('offline/') ? native.base + '/' + relative : skillsApi + relative.slice('skill-fallback'.length);
    const response = await fetch(destination, { method: 'POST', headers: { 'Content-Type': 'application/json', 'x-term1-skill-grant': grant.token }, body: request.postData() });
    const json = await response.json();
    if (json.receipt?.kind === 'seal' && !lost) { lost = true; return route.abort(); }
    return route.fulfill({ status: response.status, headers: cors, json });
  });

  await page.goto(link.href);
  await page.locator('#activationCode').fill(grant.activationCode);
  await page.getByRole('button', { name: 'Kiểm tra thông tin học viên' }).click();
  await page.locator('#identityConfirm').waitFor({ state: 'visible' });
  await page.click('#confirmIdentity');
  await page.getByRole('button', { name: 'Bắt đầu Writing', exact: true }).click();
  const editor = page.locator('textarea[data-writing-task="task2"]');
  await editor.waitFor();
  assert.equal(await page.locator('textarea[data-writing-outline],textarea[data-writing-task="task1"]').count(), 0);
  assert.equal(await page.evaluate(() => {
    const section = window.K56_TERM1_OFFLINE.record.sections.writing;
    return Date.parse(section.deadlineAt) - Date.parse(section.startedAt);
  }), 55 * 60000);
  disconnected = true;
  await browser.context.setOffline(true);
  await editor.fill('Bài viết <script> đã giữ.');
  await wait(page, () => window.K56_TERM1_OFFLINE.record.snapshot?.drafts?.writing?.task2 === 'Bài viết <script> đã giữ.', 'Writing lưu nháp');
  await page.reload();
  await editor.waitFor();
  assert.equal(await editor.inputValue(), 'Bài viết <script> đã giữ.');
  const saving = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Tải bài làm về máy' }).click();
  const backup = await readFile(await (await saving).path(), 'utf8');
  assert.match(backup, /Bài viết &lt;script&gt; đã giữ\./);
  assert.ok(!backup.includes(grant.token) && !backup.includes(grant.activationCode));
  await page.screenshot({ path: resolve(output, 'writing-offline.png') });
  await editor.fill(' \u200b\u00a0');
  await page.click('#submitWriting');
  await page.locator('#resultReadyView').waitFor({ state: 'visible' });
  assert.equal(await page.locator('#viewResult').isDisabled(), true);
  disconnected = false;
  await browser.context.setOffline(false);
  await wait(page, () => window.K56_TERM1_OFFLINE.pending === 0, 'Biên nhận sau mất ACK', 25000);
  assert.equal(lost, true);
  await page.click('#viewResult');
  await page.locator('#resultView').waitFor({ state: 'visible' });
  assert.equal(await page.getByText('Bài Writing trắng · 0/9').count(), 0);
  await page.screenshot({ path: resolve(output, 'writing-awaiting-release.png') });
  afterRelease = true;
  await page.reload();
  await page.click('#viewResult');
  await page.getByText('Bài Writing trắng · 0/9', { exact: true }).waitFor();
  assert.equal(await page.locator('#questionDetails details').count(), 0);
  await page.screenshot({ path: resolve(output, 'writing-result.png') });
  assert.deepEqual((await native.db.query('SELECT id FROM assessment.term_test_writing_grading_job')).rows, []);
  const grades = await native.db.query('SELECT field,grade FROM assessment.k56_portal_field_dispatch WHERE attempt_id=$1', [native.a]);
  assert.deepEqual(grades.rows.map(row => [row.field, Number(row.grade)]), [['writing', 0]]);
  browser.assertJournalFaultExercised();
  assert.deepEqual(browser.errors, []);
  await writeFile(resolve(output, 'writing-result.json'), JSON.stringify({ grade: 0, max: 9, jobs: 0, lostAck: lost }, null, 2));
});
