import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const root=new URL('../term-tests/',import.meta.url);
const read=p=>fs.readFileSync(new URL(p,root),'utf8');
const sandbox={window:{}};
for(const file of ['term-test-2-k56/test-config.js','term-test-2-k56-computer-based/passages.js','term-test-2-k56-computer-based/content.js'])vm.runInNewContext(read(file),sandbox,{timeout:5000});
const config=sandbox.window.TERM_TEST_CONFIG;
assert.equal(config.slug,'term-test-2-k56');
assert.equal(config.listening.controls.length,40);assert.equal(config.reading.controls.length,40);
assert.equal(sandbox.window.K56_TERM_TEST_CONTENT.writing.tasks.length,1);
assert.equal(sandbox.window.K56_TERM_TEST_CONTENT.writing.tasks[0].id,'task1');
assert.equal(sandbox.window.K56_TERM_TEST_CONTENT.audio.src,'');
const html=read('k56-demo/index.html');
assert.equal((html.match(/>Xem kết quả</g)||[]).length,1);
assert.ok(html.includes('../term-test-1-k56-computer-based/?class=CODEXDEMO56'));
assert.ok(html.includes('../term-test-2-k56-computer-based/?class=CODEXDEMO56'));
assert.ok(!html.includes('127.0.0.1'));
assert.ok(read('k56-test2-shared/app.js').includes('Nộp bài & chấm Writing tự động'));
assert.ok(read('term-test-2-k56-computer-based/bootstrap.js').includes('../k56-test2-shared/app.js'));
for(const name of ['server-private','assets/private'])assert.equal(fs.existsSync(new URL('term-test-2-k56-computer-based/'+name,root)),false);
console.log('K56 Test 2: cấu trúc đề, link online, một nút kết quả và tách tài nguyên riêng đều đạt.');
