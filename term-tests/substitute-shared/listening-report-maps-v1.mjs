// Reading pauses are matched to the announcements and rendered question numbers.
// Quiet windows that aren't reading time stay unverified, including review and
// section transitions. The extra margins absorb the 0.25-second measurement grid.
function profile(sha256,duration,reading,quiet){
  const audibleWindows=[];
  let start=1;
  for(const [from,to] of quiet){
    if(from-.5>start)audibleWindows.push([start,from-.5]);
    start=to+.5;
  }
  if(duration-2>start)audibleWindows.push([start,duration-2]);
  const readingGaps=reading.map(([from,to,part,first,last])=>({
    id:'before-q'+first,from,to,part,questions:first+'–'+last,
  }));
  return {version:1,sha256,duration,readingGaps,audibleWindows};
}

